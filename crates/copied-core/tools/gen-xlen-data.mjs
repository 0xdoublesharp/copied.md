// Generates src/render/xlen_data.rs from the twitter-text 3.1.0 and
// twemoji-parser 11.0.2 packages used by the ts-oracle-v1 baseline.
//
// Usage (from the repository root, after `pnpm install`):
//   node crates/copied-core/tools/gen-xlen-data.mjs node_modules/.pnpm > crates/copied-core/src/render/xlen_data.rs
import { createRequire } from 'node:module';
import { resolve } from 'node:path';

const store = resolve(process.argv[2] ?? 'node_modules/.pnpm');
const require = createRequire(import.meta.url);
const load = (path) => {
  const mod = require(resolve(store, path));
  return (mod.default ?? mod).source;
};
const tt = 'twitter-text@3.1.0/node_modules/twitter-text/dist/regexp/';

function tlds(source) {
  const inner = source.slice('(?:(?:'.length, source.indexOf(')(?='));
  return inner.split('|');
}

// Enumerates the finite language of the twemoji regex (alternation, groups,
// character classes, `?`). Works on UTF-16 code units like the JS engine.
function enumerate(source) {
  let i = 0;
  const unit = () => {
    if (source[i] === '\\') {
      if (source[i + 1] === 'u') {
        const code = parseInt(source.slice(i + 2, i + 6), 16);
        i += 6;
        return code;
      }
      i += 2;
      return source.charCodeAt(i - 1);
    }
    return source.charCodeAt(i++);
  };
  function alt() {
    const options = [seq()];
    while (source[i] === '|') {
      i++;
      options.push(seq());
    }
    return options.flat();
  }
  function seq() {
    let results = [[]];
    while (i < source.length && source[i] !== '|' && source[i] !== ')') {
      let atom;
      if (source[i] === '(') {
        i++;
        if (source.startsWith('?:', i)) i += 2;
        atom = alt();
        if (source[i] !== ')') throw new Error('unclosed group at ' + i);
        i++;
      } else if (source[i] === '[') {
        i++;
        const set = [];
        while (source[i] !== ']') {
          const start = unit();
          if (source[i] === '-' && source[i + 1] !== ']') {
            i++;
            const end = unit();
            for (let c = start; c <= end; c++) set.push([c]);
          } else {
            set.push([start]);
          }
        }
        i++;
        atom = set;
      } else {
        atom = [[unit()]];
      }
      if (source[i] === '?') {
        i++;
        atom = [[], ...atom];
      }
      const next = [];
      for (const prefix of results) for (const tail of atom) next.push(prefix.concat(tail));
      results = next;
    }
    return results;
  }
  const out = alt();
  if (i !== source.length) throw new Error('trailing input at ' + i);
  return out;
}

const emoji = [...new Set(enumerate(load('twemoji-parser@11.0.2/node_modules/twemoji-parser/dist/lib/regex.js'))
  .filter((units) => units.length > 0)
  .map((units) => String.fromCharCode(...units))
  .filter((s) => s.isWellFormed()))].sort((a, b) => Buffer.compare(Buffer.from(a), Buffer.from(b)));

const rust = (s) => JSON.stringify(s).replace(/\\u([0-9a-f]{4})/gi, (_, h) => '\\u{' + h + '}');
const lines = [
  '//! Generated by `tools/gen-xlen-data.mjs` from twitter-text 3.1.0 and',
  '//! twemoji-parser 11.0.2. Do not edit by hand.',
  '',
  '/// Generic and country-code TLDs in twitter-text match order.',
  '#[rustfmt::skip]',
  'pub(crate) static TLDS: &[&str] = &[',
  ...[...tlds(load(tt + 'validGTLD.js')), ...tlds(load(tt + 'validCCTLD.js'))].map((t) => '    ' + rust(t) + ','),
  '];',
  '',
  '/// Every emoji sequence twemoji-parser recognizes, sorted by UTF-8 bytes for binary search.',
  '#[rustfmt::skip]',
  'pub(crate) static EMOJI: &[&str] = &[',
  ...emoji.map((e) => '    ' + rust(e) + ','),
  '];',
  '',
];
process.stdout.write(lines.join('\n'));
